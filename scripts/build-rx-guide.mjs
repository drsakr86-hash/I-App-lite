// Turns the plain-text export of the clinic "Rx in a minute" guide into src/modules/rx-guide/data.js.
// Usage: node scripts/build-rx-guide.mjs <guide.txt>
// The text is kept exactly as written (doses included); only the structure is recovered:
//   "Chapter N · Name" lines open a chapter, "N.M" + a title line open a card, and the five marker lines
//   (🔎 💊 ⚠️ ⛔ 📅) open the card's sections. Nothing is translated, rewritten or merged.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-rx-guide.mjs <guide.txt>'); process.exit(1); }
const lines = readFileSync(src, 'utf8').split(/\r?\n/).map(l => l.trim());

const MARKERS = { '🔎': 'check', '💊': 'rx', '⚠️': 'warn', '⛔': 'avoid', '📅': 'follow' };
const marker = l => MARKERS[l] || MARKERS[l.replace(/️/g, '') + '️'] || MARKERS[l.replace(/️/g, '')] || null;
const NUM = /^\d+\.\d+(?:\.\d+)?$/;
const CHAPTER = /^Chapter (\d+) · (.+)$/;
const FLOWERS = /^[🌸🌼🌷🌺🌻💐🌹🌿]$/u;

const chapters = [];
const cards = [];
let chapter = null;
let card = null;
let section = null;
let credit = [];
let ended = false;

for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  if (!l) continue;
  if (ended) { credit.push(l); continue; }
  const ch = CHAPTER.exec(l);
  if (ch) { chapter = { n: Number(ch[1]), name: ch[2] }; chapters.push(chapter); card = null; section = null; continue; }
  if (!chapter) continue;
  if (FLOWERS.test(l)) continue;
  if (l.startsWith('بالتوفيق')) { ended = true; card = null; section = null; continue; }
  if (NUM.test(l)) {
    let j = i + 1;
    while (j < lines.length && !lines[j]) j++;
    const title = lines[j];
    const urgent = title.includes('🚨');
    card = { id: 'c' + String(cards.length + 1).padStart(3, '0'), num: l, chapter: chapter.n, title: title.replace('🚨', '').trim(), urgent, sections: [] };
    cards.push(card);
    section = null;
    i = j;
    continue;
  }
  if (!card) continue;
  const m = marker(l);
  if (m) { section = { kind: m, lines: [] }; card.sections.push(section); continue; }
  if (section) section.lines.push(l);
}

const out = {
  title: 'روشتة في دقيقة',
  author: 'Dr. Reem Fawzy',
  credit: credit.join(' '),
  chapters,
  cards
};
const body = '// GENERATED by scripts/build-rx-guide.mjs from the clinic "Rx in a minute" guide (prepared by Dr. Reem Fawzy,\n' +
  '// condensed from The Wills Eye Manual). Do not edit by hand: re-run the script on a new export of the guide.\n' +
  'export default ' + JSON.stringify(out, null, 1) + ';\n';
writeFileSync(new URL('../src/modules/rx-guide/data.js', import.meta.url), body);
const empty = cards.filter(c => !c.sections.length);
console.log(`chapters ${chapters.length}, cards ${cards.length}, urgent ${cards.filter(c => c.urgent).length}, cards without sections ${empty.length}`);
if (empty.length) console.log('no sections:', empty.map(c => c.num + ' ' + c.title).join(' | '));
